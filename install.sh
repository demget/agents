#!/bin/sh
# Wires ~/.agents into ~/.claude and ~/.codex. Safe to run any number of times.
set -eu
A="$HOME/.agents" C="$HOME/.claude" X="$HOME/.codex"
backup="$C/backups/agents-$(date +%Y%m%d-%H%M%S)"
mkdir -p "$C/skills" "$X"

# link TARGET PATH: point PATH at TARGET, moving a real file or directory there into $backup.
link() {
  if [ -e "$2" ] && [ ! -L "$2" ]; then mkdir -p "$backup" && mv "$2" "$backup/"; fi
  ln -sfn "$1" "$2"
}

# compose FILE: rebuild FILE from stdin plus the marked blocks other tools keep in it
# (<!-- name: … --> … <!-- /name -->).
compose() {
  blocks=$(awk '/^<!-- [a-z0-9-]+:/ {keep = 1} keep {print} /^<!-- \/[a-z0-9-]+ -->/ {keep = 0}' "$1" 2>/dev/null || true)
  { cat; [ -z "$blocks" ] || printf '\n%s\n' "$blocks"; } > "$1.agents-new"
  if cmp -s "$1.agents-new" "$1"; then rm "$1.agents-new"; else mv "$1.agents-new" "$1"; fi
}

# Claude imports the shared rules; Codex has no imports, so it gets a copy.
printf '@~/.agents/AGENTS.md\n' | compose "$C/CLAUDE.md"
{ printf '<!-- Generated by ~/.agents/install.sh from ~/.agents/AGENTS.md; edit that file. -->\n\n'; cat "$A/AGENTS.md"; } | compose "$X/AGENTS.md"

# Claude Code can replace the settings link with a plain file when it saves; keep what it saved.
if [ -f "$C/settings.json" ] && [ ! -L "$C/settings.json" ] && [ "$C/settings.json" -nt "$A/claude/settings.json" ]; then
  mv "$C/settings.json" "$A/claude/settings.json"
fi
link "$A/claude/settings.json" "$C/settings.json"

# Codex reads ~/.agents/skills itself; Claude needs a link per skill. Claude-only skills live in claude/skills.
for s in "$A"/skills/*/ "$A"/claude/skills/*/; do
  [ -d "$s" ] && s=${s%/} && link "$s" "$C/skills/${s##*/}"
done
for l in "$C"/* "$C"/skills/* "$C"/hooks/* "$C"/commands/*; do
  if [ -L "$l" ] && [ ! -e "$l" ]; then case $(readlink "$l") in *.agents/*) rm "$l" ;; esac; fi
done
